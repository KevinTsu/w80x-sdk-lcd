//FAT功能测试：格式化测试，文件写入测试，文件读取测试（基本功能）
static int fatfs_read_write_test(char *file_path)
{
	FIL fnew; //文件对象
	FRESULT res_sd;//文件操作结果
	UINT fnum; //文件成功读写数量
	BYTE ReadBuffer[256] = {0};
	
	BYTE WriteBuffer[] = "Successfully ported FatFs file system!"; //写缓存区
	
	//***********************写测试****************************
	//打开文件，如果文件不存在则创建它
    printf("\n");
	LV_DEBUG("A file write test is about to begin...\r\n");
	//打开文件，若不存在就创建
	res_sd = f_open(&fnew, file_path, FA_CREATE_ALWAYS | FA_WRITE);
	//文件打开成功
	if(res_sd == FR_OK)
	{
		LV_DEBUG("Open file successfully! Start writing data!\r\n");
		res_sd= f_write(&fnew, WriteBuffer, sizeof(WriteBuffer), &fnum);
		
		if(res_sd == FR_OK)
		{
			LV_DEBUG("The data is written successfully %d byte!\r\n", fnum);
			LV_DEBUG("Data: \"%s\"\n", WriteBuffer);
		}
		else
		{
			LV_DEBUG("Data write failed!\r\n");
		}
		
		//关闭文件
		f_close(&fnew);
	}
	
	//***********************读测试****************************
	//打开文件，如果文件不存在则创建它
    printf("\n");
	LV_DEBUG("A file reading test is about to begin...\r\n");
	// 打开文件，若不存在就创建
	res_sd = f_open(&fnew, file_path, FA_OPEN_EXISTING | FA_READ);
	//文件打开成功
	if(res_sd == FR_OK)
	{
		LV_DEBUG("Open file successfully! Start reading the data!\r\n");
        memset(ReadBuffer, 0, sizeof(ReadBuffer));
		res_sd= f_read(&fnew, ReadBuffer, sizeof(ReadBuffer), &fnum);
		
		if(res_sd == FR_OK)
		{
			LV_DEBUG("Data read successfully!\r\n");
			LV_DEBUG("Data: \"%s\"\n", ReadBuffer);
		}
		else
		{
			LV_DEBUG("Data read failed!\r\n");
		}
		//关闭文件
		f_close(&fnew);
	}
	return 0;
}

void array_jpeg_to_fatfs_test(char *save_path, const unsigned char *img_array, int size)
{
	FIL fnew; //文件对象
	UINT fnum; //文件成功读写数量

    // 获取文件信息
    FILINFO fileInfo;
    FRESULT result = f_stat(save_path, &fileInfo);
    // FRESULT result = -1;
    // 文件不存在
    if (result != FR_OK)
    {
        //***********************写入数组中jpg图片到文件系统****************************
        //打开文件，如果文件不存在则创建它
        printf("\n");
        LV_DEBUG("The image writing test is about to begin...\r\n");
        //打开文件，若不存在就创建
        result = f_open(&fnew, save_path, FA_CREATE_ALWAYS | FA_WRITE);
        //文件打开成功
        if(result == FR_OK)
        {
            LV_DEBUG("Open file successfully! Start writing data!\r\n");
            LV_DEBUG("File size: %d byte\n", size);
            result= f_write(&fnew, img_array, size, &fnum);
            if(result == FR_OK)
            {
                LV_DEBUG("The data is written successfully %d byte!\r\n", fnum);
            }
            else
            {
                LV_DEBUG("Data write failed!\r\n");
            }
            //关闭文件
            f_close(&fnew);
        }
    }
    else{
        printf("\n");
        LV_DEBUG("File already exists, skip writing!\r\n");
    }
}

