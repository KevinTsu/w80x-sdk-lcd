static FRESULT scan_files(char *path)
{
	FRESULT res;                                  // 定义结果对象
	DIR dir;                                      // 定义目录对象
	FILINFO fno;                                  // 定义静态文件信息结构对象
	res = f_opendir(&dir,path);                   // 打开目录，返回状态 和 目录对象的指针
	if(res == FR_OK){
        printf("--------------------------------------------------\r\n");
		for(;;){
			res = f_readdir(&dir, &fno);          // 读取目录，返回状态 和 文件信息的指针
			if(res != FR_OK || fno.fname[0] == 0) 
 				break;                            // 若打开失败 或 到结尾，则退出
			if(fno.fattrib & AM_DIR){
				printf("--   %s/\n",fno.fname);
			}
            else{
                // char* ext = strrchr(fno.fname, '.'); // 获取文件后缀
                // if (ext != NULL && strcmp(ext + 1, "wav") == 0) { // 如果后缀为wav
                    printf("--   %s\n",fno.fname); // 是文件
                // }
			}
		}
        printf("--------------------------------------------------\r\n");
	}
	else{
		printf("File opening failure - %d\n",res); //打开失败
	}
	f_closedir(&dir); //关闭目录
	return res; //返回状态
}

//FAT功能测试：格式化测试，文件写入测试，文件读取测试（基本功能）
static int fatfs_func(void)
{
	FATFS fs; //FatFs文件系统对象
	FIL fnew; //文件对象
	FRESULT res_sd;//文件操作结果
	UINT fnum; //文件成功读写数量
	BYTE ReadBuffer[256] = {0};
	BYTE work[FF_MAX_SS];
	BYTE WriteBuffer[] = "Successfully ported FatFs file system!"; //写缓存区
	

 	// wm_sdio_host_config(0);

	//挂载SD卡
	res_sd = f_mount(&fs, "4:", 1);
	
	//***********************格式化测试****************************
	if(res_sd == FR_NO_FILESYSTEM)
	{
		while(1)
		{
			TEST_DEBUG("The SD card does not have a file system and is about to be formatted...\r\n");
			//格式化
			
			res_sd = f_mkfs("4:", 0, work, sizeof(work));
			
			if(res_sd == FR_OK)
			{
				TEST_DEBUG("SD card formatted successfully!\r\n");
				//格式化后先取消挂载
				res_sd = f_mount(NULL, "4:", 1);
				//再重新挂载
				res_sd = f_mount(&fs, "4:", 1);
				break;
			}
			else
			{
				TEST_DEBUG("File formatting failed! Error code: %d; will try again...\r\n",res_sd);
                tls_os_time_delay(HZ);
			}
		}
	}
	else if(res_sd != FR_OK)
	{
		TEST_DEBUG("Failed to mount file system! Probably because file initialization failed! Error code: %d\r\n", res_sd);
	}
	else
	{
		TEST_DEBUG("The file system is mounted successfully. Read and write tests can be performed!\r\n");
	}
	
	//***********************写测试****************************
	//打开文件，如果文件不存在则创建它
    printf("\n");
	TEST_DEBUG("A file write test is about to begin...\r\n");
	//打开文件，若不存在就创建
	res_sd = f_open(&fnew, "4:FatFsTestFiles.txt", FA_CREATE_ALWAYS | FA_WRITE);
	//文件打开成功
	if(res_sd == FR_OK)
	{
		TEST_DEBUG("Open file successfully! Start writing data!\r\n");
		res_sd= f_write(&fnew, WriteBuffer, sizeof(WriteBuffer), &fnum);
		
		if(res_sd == FR_OK)
		{
			TEST_DEBUG("The data is written successfully %d byte!\r\n", fnum);
			TEST_DEBUG("Data: \"%s\"\n", WriteBuffer);
		}
		else
		{
			TEST_DEBUG("Data write failed!\r\n");
		}
		
		//关闭文件
		f_close(&fnew);
	}
	
	//***********************读测试****************************
	//打开文件，如果文件不存在则创建它
    printf("\n");
	TEST_DEBUG("A file reading test is about to begin...\r\n");
	// 打开文件，若不存在就创建
	res_sd = f_open(&fnew, "4:FatFsTestFiles.txt", FA_OPEN_EXISTING | FA_READ);
	//文件打开成功
	if(res_sd == FR_OK)
	{
		TEST_DEBUG("Open file successfully! Start reading the data!\r\n");
        memset(ReadBuffer, 0, sizeof(ReadBuffer));
		res_sd= f_read(&fnew, ReadBuffer, sizeof(ReadBuffer), &fnum);
		
		if(res_sd == FR_OK)
		{
			TEST_DEBUG("Data read successfully!\r\n");
			TEST_DEBUG("Data: \"%s\"\n", ReadBuffer);
		}
		else
		{
			TEST_DEBUG("Data read failed!\r\n");
		}
		//关闭文件
		f_close(&fnew);
	}

    // 获取文件信息
    FILINFO fileInfo;
    FRESULT result = f_stat("4:dog.jpg", &fileInfo);
    // FRESULT result = -1;
    // 文件不存在
    if (result != FR_OK)
    {
        //***********************写入jpg图片****************************
        //打开文件，如果文件不存在则创建它
        printf("\n");
        TEST_DEBUG("The image writing test is about to begin...\r\n");
        //打开文件，若不存在就创建
        res_sd = f_open(&fnew, "4:dog.jpg", FA_CREATE_ALWAYS | FA_WRITE);
        //文件打开成功
        if(res_sd == FR_OK)
        {
            TEST_DEBUG("Open file successfully! Start writing data!\r\n");
            printf("---> sizeof: %d\n", sizeof(image_dog_jpg_data));
            res_sd= f_write(&fnew, image_dog_jpg_data, sizeof(image_dog_jpg_data), &fnum);
            
            if(res_sd == FR_OK)
            {
                TEST_DEBUG("The data is written successfully %d byte!\r\n", fnum);
            }
            else
            {
                TEST_DEBUG("Data write failed!\r\n");
            }
            
            //关闭文件
            f_close(&fnew);
        }
    }
    else{
        printf("\n");
        TEST_DEBUG("File already exists, skip writing!\r\n");
    }

    extern FRESULT scan_files(char *path);
    printf("---> Scanning files:\r\n");
    scan_files("4:/");
	//取消挂载文件系统

	// f_mount(NULL, "4:", 1);
	return 0;
}

